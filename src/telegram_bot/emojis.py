def get_random_emoji() -> str:
    """Get a random emoji from the emoji list.

    Returns:
        A random emoji string.
    """
    return random.choice(EMOJI_LIST)


def get_random_emojis(count: int = 1) -> list[str]:
    """Get multiple random emojis.

    Args:
        count: Number of emojis to return (default: 1).

    Returns:
        List of random emoji strings.
    """
    return [get_random_emoji() for _ in range(count)]


def add_random_emoji_to_text(text: str, emoji_count: int = 1) -> str:
    """Add random emoji(s) to the end of a text message.

    Args:
        text: The original text message.
        emoji_count: Number of emojis to add (default: 1).

    Returns:
        Text with random emoji(s) appended.
    """
    if not text.strip():
        return get_random_emoji()

    emojis = " ".join(get_random_emojis(emoji_count))
    return f"{text.strip()} {emojis}"
